// Generates FRENCH_REVIEW.md from the shipped Defs + French DefInjected XML.
// Per TRANSLATIONS.md section 3 ("Review file"): Original/English/French columns,
// grouped by file, shipped order, never hand-edited.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const MOD = join(ROOT, 'Mod');

function readXml(path) { return readFileSync(path, 'utf8'); }

function splitDefBlocks(xml, tag) {
  const blocks = {};
  const re = new RegExp(`<${tag}[^>]*>([\\s\\S]*?)</${tag}>`, 'g');
  let m;
  while ((m = re.exec(xml))) {
    const body = m[1];
    const dn = /<defName>([^<]*)<\/defName>/.exec(body);
    if (dn) blocks[dn[1]] = body;
  }
  return blocks;
}

function firstTag(body, tag) {
  const m = new RegExp(`<${tag}>([^<]*)<\\/${tag}>`).exec(body);
  return m ? m[1].replace(/&apos;/g, "'").replace(/&amp;/g, '&') : null;
}

function parseFrenchLanguageData(xml) {
  const rows = [];
  const re = /^\s*<([A-Za-z0-9_.]+)>([^<]*)<\/\1>\s*$/;
  for (const line of xml.split('\n')) {
    const m = re.exec(line);
    if (m) rows.push([m[1], m[2].replace(/&apos;/g, "'").replace(/&amp;/g, '&')]);
  }
  return rows;
}

// path-derived English text for list items without an explicit key (tools[], body parts):
// RimWorld's DefInjected path segment for these is the untranslated label with
// spaces replaced by underscores, so the segment itself recovers the English text.
function englishFromPathSegment(seg) {
  return seg.replace(/_/g, ' ');
}

function reviewRowsForFile(frenchPath, defsByTag, opts) {
  const french = readXml(frenchPath);
  const pairs = parseFrenchLanguageData(french);
  const rows = [];
  for (const [key, fr] of pairs) {
    const segs = key.split('.');
    const defName = segs[0];
    const field = segs[segs.length - 1];
    let block = null;
    for (const tag of opts.tags) { if (defsByTag[tag][defName]) { block = defsByTag[tag][defName]; break; } }
    let en = null;
    if (segs.length === 2 && (field === 'label' || field === 'description')) {
      en = firstTag(block || '', field);
    } else if (key.endsWith('.race.meatLabel')) {
      en = firstTag(block || '', 'meatLabel');
    } else if (/\.lifeStages\.\w+\.(label|labelPlural)$/.test(key)) {
      const stageMatch = /lifeStages>([\s\S]*)<\/lifeStages/.exec(block || '');
      en = stageMatch ? firstTag(stageMatch[1], field) : null;
    } else {
      // customLabel / tool label path segments: last-but-one segment is the sanitized English text
      en = englishFromPathSegment(segs[segs.length - 2]);
    }
    rows.push({ key, en: en ?? '(?)', fr });
  }
  return rows;
}

function toTable(rows) {
  const lines = ['| Key or path | Original | English | French |', '|---|---|---|---|'];
  for (const r of rows) lines.push(`| \`${r.key}\` | ${r.en} | ${r.en} | ${r.fr} |`);
  return lines.join('\n');
}

const bodyDefs = splitDefBlocks(readXml(join(MOD, 'Defs/Bodies/Bodies_Ebbb.xml')), 'BodyDef');
const thingDefsRaces = splitDefBlocks(readXml(join(MOD, 'Defs/ThingDefs_Races/Races_Ebbb.xml')), 'ThingDef');
const pawnKindDefs = splitDefBlocks(readXml(join(MOD, 'Defs/ThingDefs_Races/Races_Ebbb.xml')), 'PawnKindDef');
const thingDefsItems = { ...splitDefBlocks(readXml(join(MOD, 'Defs/ThingDefs_Items/Items_Resource_Ebbb.xml')), 'ThingDef'), ...splitDefBlocks(readXml(join(MOD, 'Defs/FleshTypeDefs/FleshType.xml')), 'ThingDef') };

const head = process.env.GIT_HEAD_SHA || '(uncommitted working tree)';

const bodyRows = reviewRowsForFile(join(MOD, 'Languages/French/DefInjected/BodyDef/Ebbbs.xml'), { BodyDef: bodyDefs }, { tags: ['BodyDef'] });
const kindRows = reviewRowsForFile(join(MOD, 'Languages/French/DefInjected/PawnKindDef/Ebbbs.xml'), { PawnKindDef: pawnKindDefs }, { tags: ['PawnKindDef'] });
const thingRows = reviewRowsForFile(join(MOD, 'Languages/French/DefInjected/ThingDef/Ebbbs.xml'), { ThingDef: { ...thingDefsRaces, ...thingDefsItems } }, { tags: ['ThingDef'] });

const out = `# French review — Ebbbs Renew

Generated by \`_tools/Generate-FrenchReview.mjs\`, revision: ${head}.

No source language other than English: this mod was not ported from another language,
so Original = English throughout.

No text in this mod agrees with a pawn's own gender (no \`{PAWN_gender ? ...}\` switch
anywhere): every French string below names an animal, a body part or an item, never a
colonist, so the three-segment gender-agreement rule in TRANSLATIONS.md does not apply here.

## Languages/French/DefInjected/BodyDef/Ebbbs.xml

${toTable(bodyRows)}

## Languages/French/DefInjected/PawnKindDef/Ebbbs.xml

${toTable(kindRows)}

## Languages/French/DefInjected/ThingDef/Ebbbs.xml

${toTable(thingRows)}
`;

writeFileSync(join(ROOT, 'FRENCH_REVIEW.md'), out, 'utf8');
console.log(`FRENCH_REVIEW.md written: ${bodyRows.length + kindRows.length + thingRows.length} rows`);
